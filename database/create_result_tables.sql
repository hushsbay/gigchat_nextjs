-- result_condition 테이블 생성 (일자리 조건 저장)
CREATE TABLE public.result_condition (
	id int8 GENERATED BY DEFAULT AS IDENTITY(
		INCREMENT BY 1 
		MINVALUE 1 
		MAXVALUE 9223372036854775807 
		START 1 
		CACHE 1 
		NO CYCLE
	) NOT NULL,
	jobseeker_id int8 NOT NULL,
	condition_data jsonb NOT NULL,
	created_at timestamp(6) NOT NULL DEFAULT now(),
	CONSTRAINT result_condition_pkey PRIMARY KEY (id),
	CONSTRAINT fk_result_condition_jobseeker FOREIGN KEY (jobseeker_id) 
		REFERENCES public.jobseeker_profiles(id) 
		ON DELETE CASCADE
);

-- 인덱스 생성 (jobseeker_id는 unique - 사용자당 1개만 저장)
CREATE UNIQUE INDEX idx_result_condition_jobseeker_id ON public.result_condition USING btree (jobseeker_id);

-- 코멘트 추가
COMMENT ON TABLE public.result_condition IS '사용자별 최근 일자리 조건 저장';
COMMENT ON COLUMN public.result_condition.id IS '조건 ID';
COMMENT ON COLUMN public.result_condition.jobseeker_id IS '구직자 ID (jobseeker_profiles 참조)';
COMMENT ON COLUMN public.result_condition.condition_data IS '조건 데이터 (JSON 형식)';
COMMENT ON COLUMN public.result_condition.created_at IS '저장 시간';


-- result_search 테이블 생성 (검색 결과 저장)
CREATE TABLE public.result_search (
	id int8 GENERATED BY DEFAULT AS IDENTITY(
		INCREMENT BY 1 
		MINVALUE 1 
		MAXVALUE 9223372036854775807 
		START 1 
		CACHE 1 
		NO CYCLE
	) NOT NULL,
	jobseeker_id int8 NOT NULL,
	job_id int8 NOT NULL,
	created_at timestamp(6) NOT NULL DEFAULT now(),
	CONSTRAINT result_search_pkey PRIMARY KEY (id),
	CONSTRAINT fk_result_search_jobseeker FOREIGN KEY (jobseeker_id) 
		REFERENCES public.jobseeker_profiles(id) 
		ON DELETE CASCADE,
	CONSTRAINT fk_result_search_job FOREIGN KEY (job_id) 
		REFERENCES public.jobs(id) 
		ON DELETE CASCADE
);

-- 인덱스 생성
CREATE INDEX idx_result_search_jobseeker_id ON public.result_search USING btree (jobseeker_id);
CREATE INDEX idx_result_search_created_at ON public.result_search USING btree (created_at DESC);

-- 코멘트 추가
COMMENT ON TABLE public.result_search IS '사용자별 최근 검색 결과 저장';
COMMENT ON COLUMN public.result_search.id IS '검색 결과 ID';
COMMENT ON COLUMN public.result_search.jobseeker_id IS '구직자 ID (jobseeker_profiles 참조)';
COMMENT ON COLUMN public.result_search.job_id IS '일자리 ID (job_postings 참조)';
COMMENT ON COLUMN public.result_search.created_at IS '저장 시간';
